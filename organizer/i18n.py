_current = "pt_BR"

def set_language(lang: str):
    global _current
    if lang in TRANSLATIONS:
        _current = lang

def get_language() -> str:
    return _current

def t(key: str, **kwargs) -> str:
    d = TRANSLATIONS.get(_current, TRANSLATIONS["pt_BR"])
    s = d.get(key, TRANSLATIONS["pt_BR"].get(key, key))
    if kwargs:
        try:
            s = s.format(**kwargs)
        except Exception:
            pass
    return s

def load_language_from_config():
    try:
        cfg = json.loads(CONFIG_FILE.read_text(encoding="utf-8"))
        set_language(cfg.get("language", "pt_BR"))
    except Exception:
        set_language("pt_BR")
